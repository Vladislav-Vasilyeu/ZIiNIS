_SYNONYMS = {
    word: tuple(candidate for candidate in group if candidate != word)
    for group in _SYNONYM_GROUPS
    for word in group
}


def _match_case(source: str, replacement: str) -> str:
    if source.isupper():
        return replacement.upper()
    if source[:1].isupper():
        return replacement[:1].upper() + replacement[1:]
    return replacement


class ClassicSynonymAdapter(BaseLLMAdapter):
    """Детерминированная замена по небольшому встроенному словарю."""

    name = "classic"

    def supports_word(self, word: str) -> bool:
        return word.casefold() in _SYNONYMS

    async def _ensure_client(self) -> None:
        return None

    async def _request_candidates(
        self,
        text: str,
        word: str,
        num_candidates: int,
        *,
        temperature: float,
    ) -> list[str]:
        candidates = _SYNONYMS.get(word.casefold())
        if candidates is None:
            raise RuntimeError(f"Слово «{word}» отсутствует во встроенном словаре")
        return [_match_case(word, candidate) for candidate in candidates[:num_candidates]]
